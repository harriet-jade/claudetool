const rpcProto = `syntax = "proto3";

service Seizures {
    // ProcessInformationRequest downloads the file, then loops over each row.
    rpc ProcessInformationRequest(ProcessInformationRequestRequest) returns (ProcessInformationRequestResponse) {}
}
`

func TestContainsComment(t *testing.T) {
	// GIVEN - Changed text that may or may not have a comment.
	cases := map[string]bool{
		"// increment i\ni++":                     true,
		"/* increment i */\ni++":                  true,
		"# increment i\ni += 1":                   true,
		`"""Returns the user."""`:                 true,
		"-- select the active users\nSELECT 1":    true,
		"const n = 1 // the number one":           true,
		"x := \"https://example.com\"\ni++\n":     false,
		"set -euo pipefail\ncurl --fail --silent": false,
	}
	for text, want := range cases {
		t.Run(text, func(t *testing.T) {
			// WHEN - The quick check runs.
			got := containsComment(text)

			// THEN - Only text with a comment marker starts a review.
			if got != want {
				t.Errorf("containsComment(%q) = %v, want %v", text, got, want)
			}
		})
	}
}

func TestCommitChecksPassesOnCommentsAdvice(t *testing.T) {
	// GIVEN - A git repo with no Go code, and a new proto file whose RPC has a comment...
	root := newEmptyRepo(t)
	writeRepoFile(t, root, "seizures.proto", rpcProto)
	// ...and a comments review that finds a problem.
	prompt := stubCommitReviewer(t, &commentsReviewer, "REVISE\n### seizures.proto: ProcessInformationRequest downloads\nPrinciple: RPC comments")

	// WHEN - Claude tries to commit.
	code, stdout, stderr := runCommitChecksWithOutput(t, root, `git commit -m "change"`)

	// THEN - The commit is allowed, and Claude gets the reviewer's advice...
	if code != 0 {
		t.Fatalf("exit = %d, want 0 (allow); stderr: %s", code, stderr)
	}
	if !strings.Contains(stdout, "Principle: RPC comments") {
		t.Errorf("stdout = %q, want the reviewer’s advice", stdout)
	}
	// ...and the reviewer was given the proto file and the principles.
	if !strings.Contains(*prompt, "NEW FILE seizures.proto") {
		t.Errorf("prompt does not contain the proto file:\n%s", *prompt)
	}
	if !strings.Contains(*prompt, "### RPC comments") {
		t.Errorf("prompt does not contain the RPC comments principle:\n%s", *prompt)
	}
}

func TestCommitChecksSkipsCommentsReviewWithoutNewComments(t *testing.T) {
	// GIVEN - A git repo with a committed proto file that has a comment...
	root := newEmptyRepo(t)
	writeRepoFile(t, root, "seizures.proto", rpcProto)
	commitAll(t, root)
	// ...and a change to a line that is not a comment.
	writeRepoFile(t, root, "seizures.proto", strings.Replace(rpcProto, "service Seizures", "service TGSSSeizures", 1))
	prompt := stubCommitReviewer(t, &commentsReviewer, "REVISE\n- bad")

	// WHEN - Claude tries to commit.
	code, stdout, stderr := runCommitChecksWithOutput(t, root, `git commit -m "change"`)

	// THEN - The commit is allowed with no advice, because the change adds no comment...
	if code != 0 || stdout != "" {
		t.Fatalf("exit = %d, stdout = %q, want 0 and no output; stderr: %s", code, stdout, stderr)
	}
	// ...and the reviewer does not run.
	if *prompt != "" {
		t.Errorf("reviewer ran, but the change adds no comment:\n%s", *prompt)
	}
}

func TestCommitChecksSkipsGeneratedProtoCode(t *testing.T) {
	// GIVEN - A git repo with a new generated Go file that has comments.
	root := newEmptyRepo(t)
	writeRepoFile(t, root, "seizures.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n")
	prompt := stubCommitReviewer(t, &commentsReviewer, "REVISE\n- bad")

	// WHEN - The comments review runs.
	feedback := reviewComments(root)

	// THEN - It does not review the generated file.
	if feedback != "" || *prompt != "" {
		t.Errorf("feedback = %q, prompt = %q, want no review", feedback, *prompt)
	}
}

func newEmptyRepo(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	root := t.TempDir()
	if out, err := exec.Command("git", "init", "-q", root).CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
	return root
}

func commitAll(t *testing.T, root string) {
	t.Helper()
	if out, err := exec.Command("git", "-C", root, "add", "-A").CombinedOutput(); err != nil {
		t.Fatalf("git add: %v\n%s", err, out)
	}
	commit := exec.Command("git", "-C", root, "-c", "user.name=test", "-c", "user.email=test@example.com", "commit", "-q", "-m", "first")
	if out, err := commit.CombinedOutput(); err != nil {
		t.Fatalf("git commit: %v\n%s", err, out)
	}
}

func runCommitChecksWithOutput(t *testing.T, cwd, command string) (code int, stdout, stderr string) {
	t.Helper()
	toolInput, _ := json.Marshal(BashInput{Command: command})
	input, _ := json.Marshal(Input{HookEventName: "PreToolUse", ToolName: "Bash", ToolInput: toolInput, CWD: cwd})
	var out, errOut bytes.Buffer
	code = Run([]string{"commit-checks"}, bytes.NewReader(input), &out, &errOut)
	return code, out.String(), errOut.String()
}
